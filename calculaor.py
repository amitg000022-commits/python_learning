num1 = float(input("Enter NUMBER 1 :"))
operator = input("select : + , - , * , / :" )
num2 = float(input("Enter Number 2 :"))

if operator == "+":
    result = num1 + num2
    print("your result is :", result)

elif operator == "-":
    result = num1 - num2
    print("your result is :", result)

elif operator == "*":
    result = num1 * num2
    print("your result is :", result)

elif operator == "/":
    result = num1 / num2
    print("your result is :", result)

